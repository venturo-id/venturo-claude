#!/usr/bin/env python3
"""Dispatcher ambang struktur per bahasa — satu skema output untuk semua.

    thresholds.py [-all] [--rules structural.md] file.py file.tsx:10-20,40-41 ...

| Bahasa | Analyzer | Butuh |
|---|---|---|
| Go | go-thresholds (go/ast) — presisi | `go` |
| Python | analyze_python (ast) — presisi | — |
| TS/JS | ts-thresholds.cjs (TypeScript compiler API) — presisi | `node` + `node_modules/typescript` project |
| TS/JS tanpa itu, PHP, Swift, Kotlin, Dart, Java | analyze_clike — heuristik | — |

Output = skema go-thresholds (schema_version 1) + per file `language`,
`analyzer` (precise|heuristic), `ui_component`, dan per pelanggaran `language`
+ `heuristic`. Ambang dibaca dari rules/quality-score/structural.md.
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys

import analyze_clike
import analyze_python
import kinerja_lib as lib

TS_SCRIPT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ts-thresholds.cjs")

LANG_BY_EXT = {
    ".go": "go", ".py": "python",
    ".ts": "typescript", ".tsx": "typescript", ".mts": "typescript", ".cts": "typescript",
    ".js": "javascript", ".jsx": "javascript", ".mjs": "javascript", ".cjs": "javascript",
    ".php": "php", ".swift": "swift", ".kt": "kotlin", ".kts": "kotlin", ".dart": "dart", ".java": "java",
    ".vue": "vue", ".svelte": "svelte",
}
UI_EXTS = {".tsx", ".jsx", ".vue", ".svelte"}
PRECISE_CAPABLE = {"go", "python", "typescript", "javascript"}

THRESHOLD_CATEGORY = {
    "function_length": "oversized-function",
    "function_complexity": "excessive-complexity",
    "file_length": "oversized-file",
    "ui_component_length": "oversized-component",
    "parameter_count": "too-many-parameters",
    "nesting_depth": "deep-nesting",
    "magic_values": "magic-value",
}
FUNC_CHECKS = [
    ("function_length", "lines", "fungsi %d baris > %d"),
    ("function_complexity", "complexity", "kompleksitas %d cabang > %d"),
    ("nesting_depth", "nesting", "nesting %d level > %d"),
    ("parameter_count", "params", "%d parameter > %d"),
]

VENDOR_DIRS = {"node_modules", "vendor", "dist", "build", ".next", "out", "coverage", "Pods", "DerivedData",
               ".dart_tool", ".gradle", "__pycache__", ".venv", "venv", ".turbo", ".nuxt", ".svelte-kit"}
_GENERATED_RE = re.compile(r"Code generated .* DO NOT EDIT|@generated|<auto-generated|DO NOT EDIT", re.I)


def language_of(path):
    return LANG_BY_EXT.get(os.path.splitext(path)[1].lower())


def is_vendor(path):
    parts = path.replace(os.sep, "/").split("/")
    name = parts[-1]
    return (any(p in VENDOR_DIRS for p in parts[:-1]) or name.endswith((".min.js", ".d.ts", ".pb.go"))
            or name in lib.LOCKFILES)


def is_generated(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            head = fh.read(1500)
    except OSError:
        return False
    return bool(_GENERATED_RE.search(head))


def is_test(path):
    return lib.is_test_path(path)


def analyzable(path):
    """Bahasa yang didukung, bukan vendor/lockfile/generated."""
    return language_of(path) is not None and not is_vendor(path) and not is_generated(path)


# --- finalisasi seragam (meniru violations.go) -----------------------------

def _touches(ranges, start, end):
    return not ranges or any(r[0] <= end and r[1] >= start for r in ranges)


def _violation(path, line, symbol, key, value, th, fmt, heuristic):
    return {"file": path, "line": line, "symbol": symbol, "key": key, "category": THRESHOLD_CATEGORY[key],
            "value": value, "max": th[key], "detail": fmt % (value, th[key]), "heuristic": heuristic}


def finalize(raw, target, th, language, analyzer, all_functions=False):
    """Hasil mentah analyzer → laporan file berskema go-thresholds."""
    path, ranges = target["path"], target.get("ranges") or []
    heuristic = analyzer != "precise"
    rep = {"path": path, "language": language, "analyzer": analyzer, "lines": raw["lines"],
           "is_test": is_test(path), "touched": _touches(ranges, 1, max(raw["lines"], 1)),
           "ui_component": bool(raw.get("ui_component")), "functions": [], "violations": []}
    if raw.get("error"):
        rep["error"] = raw["error"]
    for f in raw["functions"]:
        f = dict(f, touched=_touches(ranges, f["start"], f["end"]))
        rep["functions"].append(f)
        if f["touched"] or all_functions:
            for key, field, fmt in FUNC_CHECKS:
                if key in th and f[field] > th[key]:
                    rep["violations"].append(_violation(path, f["start"], f["name"], key, f[field], th, fmt, heuristic))
    if "magic_values" in th and not rep["is_test"]:
        seen = set()
        for hit in raw.get("magic", []):
            if hit["line"] in seen or not (all_functions or _touches(ranges, hit["line"], hit["line"])):
                continue
            seen.add(hit["line"])
            v = _violation(path, hit["line"], _symbol_at(rep["functions"], hit["line"]), "magic_values", 1, th,
                           "%d > %d", True)
            v["detail"] = "literal %s tanpa nama di logika inti" % hit["value"]
            rep["violations"].append(v)
    key = "ui_component_length" if rep["ui_component"] and "ui_component_length" in th else "file_length"
    if key in th and raw["lines"] > th[key] and (rep["touched"] or all_functions):
        fmt = "komponen UI %d baris > %d" if key == "ui_component_length" else "file %d baris > %d"
        rep["violations"].append(_violation(path, 1, "", key, raw["lines"], th, fmt, heuristic))
    return rep


def _symbol_at(functions, line):
    inside = [f for f in functions if f["start"] <= line <= f["end"]]
    return min(inside, key=lambda f: f["lines"])["name"] if inside else ""


# --- runner per bahasa -----------------------------------------------------

def find_typescript(start):
    root = lib.find_up(start, os.path.join("node_modules", "typescript", "package.json"))
    return os.path.join(root, "node_modules", "typescript") if root else None


def _run_go(targets, rules, all_functions):
    out = lib.run_go_thresholds(targets, rules=rules, all_functions=all_functions)
    if out is None:
        return None
    for rep in out["files"]:
        rep.update(language="go", analyzer="precise", ui_component=False)
        for v in rep["violations"]:
            v.setdefault("heuristic", False)
    return out["files"]


def _run_ts(node, ts_dir, targets):
    """{path: raw} lewat TypeScript compiler API; None bila gagal."""
    payload = json.dumps({"typescript": ts_dir, "files": [t["path"] for t in targets]})
    try:
        proc = subprocess.run([node, TS_SCRIPT], input=payload, capture_output=True, text=True, timeout=60)
    except (OSError, subprocess.SubprocessError):
        return None
    if proc.returncode != 0:
        return None
    return {r["path"]: r for r in json.loads(proc.stdout)["files"]}


def _read(path):
    with open(path, encoding="utf-8", errors="replace") as fh:
        return fh.read()


def _heuristic_raw(path, language):
    raw = analyze_clike.analyze(_read(path), language)
    if os.path.splitext(path)[1].lower() in UI_EXTS:
        raw["ui_component"] = True
    return raw


def _analyze_scripts(targets, th, all_functions, status):
    """TS/JS: presisi bila node + typescript project tersedia, selain itu heuristik."""
    node = shutil.which("node")
    groups = {}
    for t in targets:
        ts_dir = find_typescript(t.get("origin") or t["path"]) if node else None
        groups.setdefault(ts_dir, []).append(t)
    reports = []
    for ts_dir, group in groups.items():
        raws = _run_ts(node, ts_dir, group) if ts_dir else None
        for t in group:
            lang = language_of(t["path"])
            if raws and t["path"] in raws:
                status[lang] = "precise" if status.get(lang) != "heuristic" else "heuristic"
                reports.append(finalize(raws[t["path"]], t, th, lang, "precise", all_functions))
            else:
                status[lang] = "heuristic"
                reports.append(finalize(_heuristic_raw(t["path"], lang), t, th, lang, "heuristic", all_functions))
    return reports


RUNTIME_HINT = {"go": "butuh `go`", "typescript": "presisi butuh node + node_modules/typescript",
                "javascript": "presisi butuh node + node_modules/typescript"}


def capability(language, repo):
    """precise | heuristic | unavailable — kemampuan analyzer untuk bahasa ini di mesin & repo ini."""
    if language == "go":
        return "precise" if shutil.which("go") else "unavailable"
    if language == "python":
        return "precise"
    if language in ("typescript", "javascript"):
        node_ok = shutil.which("node") and (find_typescript(repo) or _any_typescript(repo))
        return "precise" if node_ok else "heuristic"
    return "heuristic" if language in set(LANG_BY_EXT.values()) else "unavailable"


def _any_typescript(repo):
    """node_modules/typescript di subfolder langsung (monorepo sederhana)."""
    try:
        return any(os.path.isfile(os.path.join(repo, d, "node_modules", "typescript", "package.json"))
                   for d in os.listdir(repo))
    except OSError:
        return False


def analyze(targets, rules=lib.STRUCTURAL_RULES, all_functions=False):
    """targets: [{"path": abs, "ranges": [[a,b]], "origin"?: path asli untuk resolusi node_modules}]."""
    th = lib.structural_thresholds(rules)
    by_lang, reports, status = {}, [], {}
    for t in targets:
        by_lang.setdefault(language_of(t["path"]), []).append(t)
    if by_lang.get("go"):
        go = _run_go(by_lang["go"], rules, all_functions)
        status["go"] = "precise" if go is not None else "unavailable"
        reports += go or []
    for t in by_lang.get("python", []):
        status["python"] = "precise"
        reports.append(finalize(analyze_python.analyze(_read(t["path"])), t, th, "python", "precise", all_functions))
    scripts = by_lang.get("typescript", []) + by_lang.get("javascript", [])
    if scripts:
        reports += _analyze_scripts(scripts, th, all_functions, status)
    for lang, group in by_lang.items():
        if lang in (None, "go", "python", "typescript", "javascript"):
            continue
        status[lang] = "heuristic"
        reports += [finalize(_heuristic_raw(t["path"], lang), t, th, lang, "heuristic", all_functions) for t in group]
    for rep in reports:
        for v in rep["violations"]:
            v["language"] = rep["language"]
    return {"schema_version": 1, "rules": rules, "thresholds": th, "analyzers": status, "files": reports}


def analyze_source(content, origin, ranges=None):
    """Ukur isi file (mis. versi sebelum edit) lewat file sementara bernama sama.

    origin = path asli, dipakai untuk mencari node_modules/typescript project.
    """
    import tempfile
    tmpdir = tempfile.mkdtemp(prefix="venturo-kinerja-")
    try:
        path = os.path.join(tmpdir, os.path.basename(origin))
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
        out = analyze([{"path": path, "ranges": ranges or [], "origin": origin}])
        return out["files"][0] if out["files"] else None
    finally:
        shutil.rmtree(tmpdir, ignore_errors=True)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Ambang struktur kinerja untuk file multi-bahasa.")
    ap.add_argument("files", nargs="+", help="path[:a-b,c-d]")
    ap.add_argument("-all", "--all", action="store_true", help="laporkan semua fungsi")
    ap.add_argument("--rules", default=lib.STRUCTURAL_RULES)
    args = ap.parse_args(argv)
    targets = []
    for arg in args.files:
        m = re.match(r"^(.+?):(\d+(?:-\d+)?(?:,\d+(?:-\d+)?)*)$", arg)
        path, spec = (m.group(1), m.group(2)) if m else (arg, "")
        ranges = [[int(p.split("-")[0]), int(p.split("-")[-1])] for p in spec.split(",") if p]
        targets.append({"path": os.path.abspath(path), "ranges": ranges})
    print(json.dumps(analyze(targets, args.rules, args.all), ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
